/**
 * HerNext location dataset.
 *
 * Bundled locally on purpose: the backend stores `country` as a free name
 * string (no code/ID) and has no location endpoint, so fetching a dataset at
 * runtime would add a network dependency for no data-model benefit.
 *
 * Country value format deliberately matches the existing backend payload
 * (e.g. `registerUser({ country: 'Nigeria' })`), so the dropdown values can be
 * submitted exactly as before.
 */

export interface CountryEntry {
  /** ISO 3166-1 alpha-2 code (informational; not submitted to the API). */
  code: string
  /** English country name — the value stored/sent by the backend. */
  name: string
}

