export function getCountryName(code: string): string {
  return COUNTRIES.find((entry) => entry.code === code)?.name ?? ''
}

export function getCountryCode(name: string): string {
  return COUNTRIES.find((entry) => entry.name === name)?.code ?? ''
}

/** Case-insensitive, tolerance-friendly lookup of a country name the user may
 * already have saved (e.g. "Nigeria" → true). Returns true only when an exact
 * match exists in the standardized list. */
export function isStandardCountryName(name: string): boolean {
  const normalized = name.trim().toLowerCase()
  return COUNTRIES.some((entry) => entry.name.toLowerCase() === normalized)
}

export function getSubdivisionNames(countryName: string): readonly string[] {
  return SUBDIVISIONS_BY_COUNTRY[countryName.trim()] ?? []
}